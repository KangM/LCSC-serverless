/** 小类 → 大类（同名小类只保留第一次出现的大类） */
const MINOR_TO_MAJOR = new Map<string, string>()
for (const [major, minors] of MAJOR_MINORS) {
  for (const minor of minors) {
    if (!MINOR_TO_MAJOR.has(minor)) MINOR_TO_MAJOR.set(minor, major)
  }
}

/** 大类的固定排序（只影响计数相同时的先后） */
export const MAJOR_ORDER: readonly string[] = MAJOR_MINORS.map(([major]) => major)

