/** 小类 → 大类。空值归「其他」。 */
export function majorOf(category: string | null | undefined): string {
  const name = category?.trim()
  if (!name) return FALLBACK_MAJOR
  const exact = MINOR_TO_MAJOR.get(name)
  if (exact) return exact
  for (const [pattern, major] of KEYWORD_RULES) {
    if (pattern.test(name)) return major
  }
  return FALLBACK_MAJOR
}

/**
 * 按大类聚合「小类 + 元件数」。大类/小类都按元件数降序，方便常用分类排在前面。
 */
export function groupCategories(rows: ReadonlyArray<CategoryMinor>): CategoryGroup[] {
  const map = new Map<string, CategoryGroup>()
  for (const row of rows) {
    const name = row.name.trim()
    if (!name) continue
    const major = majorOf(name)
    const group = map.get(major) ?? { major, count: 0, minors: [] }
    group.count += row.count
    group.minors.push({ name, count: row.count })
    map.set(major, group)
  }

  const orderOf = (major: string) => {
    const index = MAJOR_ORDER.indexOf(major)
    return index === -1 ? MAJOR_ORDER.length : index
  }
  return [...map.values()]
    .map((group) => ({
      ...group,
      minors: group.minors.sort((a, b) => b.count - a.count || a.name.localeCompare(b.name, 'zh')),
    }))
    .sort((a, b) => b.count - a.count || orderOf(a.major) - orderOf(b.major))
}
